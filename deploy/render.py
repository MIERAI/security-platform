#!/usr/bin/env python3
"""deploy: render the TRIGGER that calls `runner.py tick` on a host (component `deploy`, see deploy/VERSION).

The schedule lives in the instance config; a trigger only has to call `tick` every few minutes. Targets:
  launchd     macOS LaunchAgent plist (StartInterval; a sleeping Mac catches up once when it wakes)
  cron        one crontab line (any Unix with cron)
  systemd     a .service + .timer pair (Persistent=true catches up after downtime)
  termux-job  Android/Termux: the command that registers a JobScheduler job (no cron daemon needed; >= 15 min)
  wrapper     the shell wrapper every target calls (PATH, TZ, nice, log rotation, offline, errors to the log)
  env         NOT a rendering: BUILDS the runtime environment once, at deploy time (see below)
  tool-env    NOT a rendering: BUILDS a pinned external tool (cloud check engines: prowler, steampipe, scoutsuite)
Kubernetes: see deploy/kubernetes/ (a CronJob per site, the in-cluster hub, and the metrics exporter).

Offline by design: a tick never resolves or downloads dependencies. `render.py env --install DIR` builds a virtual
environment from deploy/requirements.lock (exact versions + hashes; uv when available, else python -m venv + pip;
`--find-links DIR` for air-gapped hosts) under DIR/envs/<hash> and points DIR/env at it. The wrapper's default python
is DIR/env/bin/python3 and it exports PIP_NO_INDEX / UV_OFFLINE, so a network outage cannot stop a tick: only the
collectors that need the network fail, each on its own, as coverage gaps. Hosts with JSON instance configs need no
environment at all (--python python3). A --python that resolves packages per run (`uv run --with ...`) is refused.

usage: render.py <target> --install DIR --instance FILE --data DIR [--label L] [--interval 900] [--python CMD]
                 [--path PATH] [--tz Area/City] [--nice 10] [--log FILE] [--shell /bin/sh] [--job-id N]
       render.py env --install DIR [--python python3] [--lock FILE] [--find-links DIR] [--installer auto|uv|pip]
       render.py tool-env --install DIR --tool prowler|steampipe|scoutsuite [--tool-python 3.12]

Tools (`tool-env`): each external engine lives in DIR/tools/<tool>/<hash>/ (DIR/tools/<tool>/current points at it),
built from deploy/tools/<tool>.lock (a Python tool: exact versions + hashes, its own interpreter version) or
deploy/tools/<tool>.json (a release binary: pinned version + SHA-256 per platform, pinned plugins). They are separate
from the runner's environment on purpose: a tool's dependencies never reach the runner, and AGPL/GPL tools stay
external processes. The instance points the cloud collector at DIR/tools/<tool>/current (docs/cloud.md).
"""
import argparse
import hashlib
import json
import os
import re
import shlex
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
VERSION = open(os.path.join(HERE, "VERSION")).read().strip()


ONLINE_PYTHON = re.compile(r"\buv\s+run\b|\s--with\b|\bpipx\s+run\b|\bpip\s+install\b")


def log_path(a):
    return a.log or os.path.join(a.data, "state", "runner", "tick.log")


def python_cmd(a):
    py = a.python or shlex.quote(os.path.join(a.install, "env", "bin", "python3"))
    if ONLINE_PYTHON.search(py) and not a.allow_online_python:
        sys.exit(f"render.py: --python {py!r} resolves packages on every tick (needs the network). Build the environment "
                 "once with `render.py env --install DIR` and leave --python unset (or pass a plain interpreter).")
    return py


def wrapper(a):
    log, cur = log_path(a), os.path.join(a.install, "current")
    return f"""#!{a.shell}
# generated by security-platform deploy/render.py {VERSION} - calls the runner's tick; the schedule is in the instance.
# Offline: nothing is installed or downloaded here (render.py env built the environment). Every error goes to $LOG.
{"export PATH=" + shlex.quote(a.path) if a.path else ""}
{"export TZ=" + shlex.quote(a.tz) if a.tz else ""}
export PIP_NO_INDEX=1 UV_OFFLINE=1 PYTHONNOUSERSITE=1
umask 077
LOG={shlex.quote(log)}
mkdir -p "$(dirname "$LOG")"
[ -f "$LOG" ] && [ "$(wc -c < "$LOG")" -gt 5000000 ] && mv "$LOG" "$LOG.1"
cd {shlex.quote(cur)} || {{ echo "$(date +%Y-%m-%dT%H:%M:%S%z) tick.sh: cannot enter {cur}" >> "$LOG"; exit 1; }}
nice -n {a.nice} {python_cmd(a)} runner/runner.py tick --instance {shlex.quote(a.instance)} --data {shlex.quote(a.data)} >> "$LOG" 2>&1
rc=$?
[ "$rc" -eq 0 ] || echo "$(date +%Y-%m-%dT%H:%M:%S%z) tick.sh: runner exited rc=$rc" >> "$LOG"
exit "$rc"
"""


def requirements(lock):
    """-> [(name, version)] pinned in a hash lock (name==version lines)."""
    out = []
    for line in open(lock):
        m = re.match(r"^([A-Za-z0-9_.\-]+)==([^\s\\;]+)", line)
        if m:
            out.append((m.group(1), m.group(2)))
    return out


def build_env(a):
    """Build (once) the pinned runtime environment and point <install>/env at it. Network only here, never in a tick."""
    lock = os.path.abspath(a.lock or os.path.join(HERE, "requirements.lock"))
    py = a.python or "python3"
    pyver = subprocess.run([py, "-c", "import sys; print(sys.version)"], capture_output=True, text=True, check=True).stdout
    key = hashlib.sha256(open(lock, "rb").read() + pyver.encode()).hexdigest()[:12]
    dest = os.path.join(os.path.abspath(a.install), "envs", key)
    reqs = requirements(lock)
    installer = a.installer if a.installer != "auto" else ("uv" if shutil.which("uv") else "pip")
    if not os.path.exists(os.path.join(dest, ".complete")):
        shutil.rmtree(dest, ignore_errors=True)
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        envpy = os.path.join(dest, "bin", "python3")
        if installer == "uv":
            subprocess.run(["uv", "venv", "-q", "--python", shutil.which(py) or py, dest], check=True)
            cmd = ["uv", "pip", "install", "-q", "--python", envpy, "--require-hashes", "-r", lock]
            cmd += ["--offline", "--find-links", a.find_links] if a.find_links else []
        else:
            subprocess.run([py, "-m", "venv", dest], check=True)
            cmd = [envpy, "-m", "pip", "install", "-q", "--disable-pip-version-check", "--no-input", "--require-hashes", "-r", lock]
            cmd += ["--no-index", "--find-links", a.find_links] if a.find_links else []
        if reqs:
            subprocess.run(cmd, check=True)
        # verify: every pinned distribution is importable metadata-wise at exactly its version, without the network
        check = "import importlib.metadata as m, sys; bad=[f'{n}=={v}' for n, v in %r if m.version(n) != v]; sys.exit(str(bad) if bad else 0)" % reqs
        subprocess.run([envpy, "-I", "-c", check], check=True)
        open(os.path.join(dest, ".complete"), "w").write(f"{lock}\n{pyver}")
    link = os.path.join(os.path.abspath(a.install), "env")
    tmp = f"{link}.tmp{os.getpid()}"
    os.symlink(os.path.join("envs", key), tmp)
    os.replace(tmp, link)
    return f"{os.path.join(link, 'bin', 'python3')}  (envs/{key}, {installer}, {len(reqs)} pinned)\n"


def _swap_link(link, target):
    tmp = f"{link}.tmp{os.getpid()}"
    os.symlink(target, tmp)
    os.replace(tmp, link)


def build_tool(a):
    """Build (once) a pinned external tool under <install>/tools/<tool>/<key> and point .../current at it."""
    import platform
    import urllib.request
    base = os.path.join(os.path.abspath(a.install), "tools", a.tool)
    lock = os.path.join(HERE, "tools", f"{a.tool}.lock")
    manifest = os.path.join(HERE, "tools", f"{a.tool}.json")
    if os.path.exists(lock):                                   # a Python tool, hash-locked, its own interpreter
        py = a.tool_python or "3.12"
        key = hashlib.sha256(open(lock, "rb").read() + py.encode()).hexdigest()[:12]
        dest = os.path.join(base, key)
        if not os.path.exists(os.path.join(dest, ".complete")):
            shutil.rmtree(dest, ignore_errors=True)
            os.makedirs(base, exist_ok=True)
            if shutil.which("uv"):
                subprocess.run(["uv", "venv", "-q", "--python", py, dest], check=True)
                subprocess.run(["uv", "pip", "install", "-q", "--python", os.path.join(dest, "bin", "python3"),
                                "--require-hashes", "-r", lock], check=True)
            else:
                subprocess.run([shutil.which(f"python{py}") or f"python{py}", "-m", "venv", dest], check=True)
                subprocess.run([os.path.join(dest, "bin", "python3"), "-m", "pip", "install", "-q", "--no-input",
                                "--disable-pip-version-check", "--require-hashes", "-r", lock], check=True)
            open(os.path.join(dest, ".complete"), "w").write(f"{lock}\n{py}\n")
    elif os.path.exists(manifest):                             # a release binary, checksum-pinned
        m = json.load(open(manifest))
        system, machine = platform.system().lower(), platform.machine().lower()
        machine = {"amd64": "x86_64", "aarch64": "arm64" if system == "darwin" else "aarch64",
                   "arm64": "arm64" if system == "darwin" else "aarch64"}.get(machine, machine)
        plat = f"{system}-{machine}"
        asset = m["assets"].get(plat)
        if not asset:
            sys.exit(f"render.py tool-env: {a.tool} {m['version']} has no pinned asset for {plat}")
        key = hashlib.sha256(json.dumps(m, sort_keys=True).encode() + plat.encode()).hexdigest()[:12]
        dest = os.path.join(base, key)
        if not os.path.exists(os.path.join(dest, ".complete")):
            shutil.rmtree(dest, ignore_errors=True)
            os.makedirs(os.path.join(dest, "bin"), exist_ok=True)
            arc = os.path.join(dest, asset["file"])
            urllib.request.urlretrieve(m["url"].format(version=m["version"], file=asset["file"]), arc)
            got = hashlib.sha256(open(arc, "rb").read()).hexdigest()
            if got != asset["sha256"]:
                shutil.rmtree(dest, ignore_errors=True)
                sys.exit(f"render.py tool-env: {asset['file']} checksum mismatch ({got})")
            if arc.endswith(".zip"):
                import zipfile
                zipfile.ZipFile(arc).extractall(os.path.join(dest, "bin"))
            else:
                import tarfile
                with tarfile.open(arc) as t:
                    t.extractall(os.path.join(dest, "bin"), filter="data")
            os.remove(arc)
            exe = os.path.join(dest, "bin", a.tool)
            os.chmod(exe, 0o755)
            import tempfile
            short_tmp = tempfile.mkdtemp(prefix="sp-tool-", dir="/tmp" if os.path.isdir("/tmp") else None)
            env = dict(os.environ, STEAMPIPE_INSTALL_DIR=os.path.join(dest, "home"), STEAMPIPE_UPDATE_CHECK="false",
                       STEAMPIPE_TELEMETRY="none", TMPDIR=short_tmp)   # plugin sockets: a long TMPDIR breaks them
            for plugin in m.get("plugins") or []:
                subprocess.run([exe, "plugin", "install", plugin], env=env, check=True, stdout=subprocess.DEVNULL)
                # the installer adds a default connection using the ambient credential chain: the platform writes its
                # own connection per run (collectors/cloud/engines.py), so the default one is removed
                try:
                    os.remove(os.path.join(dest, "home", "config", plugin.split("@")[0] + ".spc"))
                except OSError:
                    pass
            # first query installs the embedded database now, so a tick never downloads it
            subprocess.run([exe, "query", "select 1"], env=env, check=True, stdout=subprocess.DEVNULL)
            shutil.rmtree(short_tmp, ignore_errors=True)
            open(os.path.join(dest, ".complete"), "w").write(json.dumps(m, sort_keys=True) + "\n")
    else:
        sys.exit(f"render.py tool-env: no deploy/tools/{a.tool}.lock or .json")
    _swap_link(os.path.join(base, "current"), key)
    return f"{os.path.join(base, 'current')}  ({a.tool}, tools/{a.tool}/{key})\n"


def launchd(a):
    script = os.path.join(a.install, "tick.sh")
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- generated by security-platform deploy/render.py {VERSION} -->
<plist version="1.0">
<dict>
  <key>Label</key><string>{a.label}</string>
  <key>ProgramArguments</key><array><string>/bin/sh</string><string>{script}</string></array>
  <key>StartInterval</key><integer>{a.interval}</integer>
  <key>RunAtLoad</key><true/>
  <key>ProcessType</key><string>Background</string>
  <key>LowPriorityIO</key><true/>
  <key>StandardOutPath</key><string>{log_path(a)}</string>
  <key>StandardErrorPath</key><string>{log_path(a)}</string>
</dict>
</plist>
"""


def cron(a):
    m = max(1, a.interval // 60)
    return (f"*/{m} * * * * /bin/sh {shlex.quote(os.path.join(a.install, 'tick.sh'))} >> {shlex.quote(log_path(a))} 2>&1"
            "   # security-platform runner tick\n")


def systemd(a):
    return f"""# {a.label}.service
[Unit]
Description=security-platform runner tick
[Service]
Type=oneshot
ExecStart=/bin/sh {os.path.join(a.install, 'tick.sh')}
Nice={a.nice}
StandardOutput=append:{log_path(a)}
StandardError=append:{log_path(a)}
# {a.label}.timer
[Timer]
OnBootSec=5min
OnUnitActiveSec={a.interval}s
Persistent=true
[Install]
WantedBy=timers.target
"""


def termux_job(a):
    period = max(900, a.interval) * 1000   # Android JobScheduler: 15 minutes minimum
    return (f"termux-job-scheduler --job-id {a.job_id} --period-ms {period} --persisted true "
            f"--battery-not-low false --network any --script {shlex.quote(os.path.join(a.install, 'tick.sh'))}\n")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("target", choices=["wrapper", "launchd", "cron", "systemd", "termux-job", "env", "tool-env"])
    ap.add_argument("--install", required=True, help="install root (holds current/ and tick.sh)")
    ap.add_argument("--instance")
    ap.add_argument("--data")
    ap.add_argument("--label", default="security-platform.runner")
    ap.add_argument("--interval", type=int, default=900)
    ap.add_argument("--python", help="interpreter; default <install>/env/bin/python3 (built by `render.py env`)")
    ap.add_argument("--allow-online-python", action="store_true", help=argparse.SUPPRESS)
    ap.add_argument("--lock", help="env: hash lock (default deploy/requirements.lock)")
    ap.add_argument("--find-links", help="env: install from this local wheel directory only (air-gapped hosts)")
    ap.add_argument("--installer", choices=["auto", "uv", "pip"], default="auto")
    ap.add_argument("--tool", help="tool-env: prowler | steampipe | scoutsuite (deploy/tools/<tool>.lock or .json)")
    ap.add_argument("--tool-python", help="tool-env: interpreter version for a Python tool (default 3.12)")
    ap.add_argument("--path")
    ap.add_argument("--tz")
    ap.add_argument("--nice", type=int, default=10)
    ap.add_argument("--log")
    ap.add_argument("--job-id", type=int, default=71)
    ap.add_argument("--shell", default="/bin/sh", help="wrapper interpreter (Termux: $PREFIX/bin/sh)")
    a = ap.parse_args(argv)
    if a.target == "env":
        sys.stdout.write(build_env(a))
        return
    if a.target == "tool-env":
        if not a.tool:
            ap.error("tool-env needs --tool")
        sys.stdout.write(build_tool(a))
        return
    if not (a.instance and a.data):
        ap.error("--instance and --data are required")
    sys.stdout.write({"wrapper": wrapper, "launchd": launchd, "cron": cron, "systemd": systemd,
                      "termux-job": termux_job}[a.target](a))


if __name__ == "__main__":
    main()
