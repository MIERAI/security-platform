"""tracker adapters: where remediation tracking items live (core/remediation.py keeps them in sync).

  tracker(cfg, data_dir).sync(items) -> {"created": n, "updated": n, "closed": n}

Items carry vulnerability details (assets, checks, evidence pointers): attacker intelligence. A tracker must be at
least as private as the findings themselves.
Implemented:
  files          DEFAULT. Private markdown in the data directory: <data>/tracker/<id>.md per item and
                 <data>/tracker/README.md (index: overdue first, then severity). No network, no third party.
  github-issues  {type: github-issues, repo: owner/name, enabled: true, gh_user?: name, label?: security-platform}
                 Off unless `enabled: true`. Refuses to run unless the repository is PRIVATE (checked before every
                 sync): a public repository never receives vulnerability details. Uses the `gh` CLI. Opens an issue
                 per item, updates it when the item changes, closes it only when the ledger closed the item (a
                 collector run covered the asset), reopens it on a regression. Issue state never feeds back.
Future (interface only): jira, linear, gitlab-issues.
"""
import hashlib
import json
import os
import subprocess

VERSION = "0.1.0"
CLOSED = ("fixed", "false_positive")
ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}


def body(it):
    exc = it.get("exception") or {}
    lines = [f"- status: {it['status']}" + (" (OVERDUE)" if it.get("overdue") else ""),
             f"- severity: {it['severity']} (SLO class {it['slo_class']}), due: {it.get('due_at') or 'no SLO'}",
             f"- owner: {it['owner']} ({it['owner_source']})",
             f"- layer / check: {it['layer']} / `{it['check']}`",
             f"- asset: `{it['asset']}`",
             f"- opened: {it['opened_at']}" + (f", reopened: {it['reopened_at']} ({it['reopen_reason']})" if it.get("reopened_at") else ""),
             f"- needs a human: {'yes' if it.get('needs_human') else 'no'}"]
    if it.get("closed_at"):
        lines.append(f"- closed: {it['closed_at']} (time to remediate {it.get('time_to_remediate_days')} d)")
    if exc:
        lines.append(f"- exception: approved by {exc.get('approved_by')}, expires {exc.get('expires')}")
    if it.get("advisor_draft"):
        lines.append(f"- advisor draft (proposal only): {it['advisor_draft']}")
    lines += ["", "## Remediation", "", it.get("remediation") or "(none given by the collector)", "",
              "Closure: only a collector run that covers the asset closes this item. Exceptions: exceptions.yaml "
              "(approved_by + expires)."]
    return "\n".join(lines) + "\n"


def title(it):
    return f"[{it['severity']}] {it['title'][:160]}"


class Files:
    def __init__(self, cfg, data):
        self.dir = os.path.join(data, "tracker")

    def sync(self, items):
        os.makedirs(self.dir, exist_ok=True)
        n = {"created": 0, "updated": 0, "closed": 0}
        for it in items.values():
            p = os.path.join(self.dir, f"{it['id']}.md")
            text = f"<!-- status: {it['status']} -->\n# {title(it)}\n\nPRIVATE - attacker intelligence.\n\n" + body(it)
            old = open(p).read() if os.path.exists(p) else None
            if old == text:
                continue
            was_open = old is not None and not any(f"<!-- status: {c} -->" in old.split("\n", 1)[0] for c in CLOSED)
            n["created" if old is None else ("closed" if was_open and it["status"] in CLOSED else "updated")] += 1
            with open(p + ".tmp", "w") as f:
                f.write(text)
            os.replace(p + ".tmp", p)
        rows = sorted(items.values(), key=lambda i: (i["status"] in CLOSED, i["status"] != "open", not i.get("overdue"),
                                                     ORDER.get(i["severity"], 9), i.get("due_at") or "~"))
        L = ["# Remediation tracker", "", "PRIVATE - attacker intelligence. Generated by core/remediation.py; edit "
             "exceptions.yaml (human approval) or fix the finding, never this file.", "",
             "| state | sev | due | owner | title | item |", "|---|---|---|---|---|---|"]
        for i in rows:
            if i["status"] in CLOSED:
                continue
            state = "**OVERDUE**" if i.get("overdue") else i["status"]
            L.append(f"| {state} | {i['severity']} | {(i.get('due_at') or '-')[:10]} | {i['owner']} | "
                     f"{i['title'][:100].replace('|', '/')} | [{i['id']}]({i['id']}.md) |")
        closed = [i for i in rows if i["status"] in CLOSED]
        L += ["", f"Closed items: {len(closed)} (see items.json)."]
        with open(os.path.join(self.dir, "README.md"), "w") as f:
            f.write("\n".join(L) + "\n")
        return n


class GitHubIssues:
    def __init__(self, cfg, data):
        self.cfg, self.repo = cfg, cfg["repo"]
        self.map_path = os.path.join(data, "tracker", "github-issues.json")
        self.label = cfg.get("label", "security-platform")

    def gh(self, args, payload=None):
        env = dict(os.environ)
        if self.cfg.get("gh_user"):
            env["GH_USER"] = self.cfg["gh_user"]
        p = subprocess.run(["gh", "api", *args] + (["--input", "-"] if payload is not None else []),
                           input=json.dumps(payload) if payload is not None else None,
                           capture_output=True, text=True, timeout=60, env=env)
        if p.returncode != 0:
            raise RuntimeError(f"gh api {args[0]} rc={p.returncode}: {p.stderr.strip()[-160:]}")
        return json.loads(p.stdout or "{}")

    def sync(self, items):
        if not self.cfg.get("enabled"):
            return {"created": 0, "updated": 0, "closed": 0, "skipped": "github-issues tracker not enabled"}
        repo = self.gh([f"repos/{self.repo}"])
        if repo.get("private") is not True:
            raise PermissionError(f"tracker github-issues: {self.repo} is not private; vulnerability details never "
                                  "go to a public repository")
        m = json.load(open(self.map_path)) if os.path.exists(self.map_path) else {}
        n = {"created": 0, "updated": 0, "closed": 0}
        for it in sorted(items.values(), key=lambda i: i["id"]):
            rec = m.get(it["id"])
            want = "closed" if it["status"] in CLOSED else "open"
            payload = {"title": title(it), "body": body(it)}
            h = hashlib.sha256(json.dumps([payload, want]).encode()).hexdigest()
            if rec is None:
                if want == "closed":
                    continue
                r = self.gh([f"repos/{self.repo}/issues", "-X", "POST"], dict(payload, labels=[self.label]))
                m[it["id"]] = {"number": r["number"], "hash": h}
                n["created"] += 1
            elif rec["hash"] != h:
                patch = dict(payload, state=want)
                if want == "closed":
                    patch["state_reason"] = "completed" if it["status"] == "fixed" else "not_planned"
                self.gh([f"repos/{self.repo}/issues/{rec['number']}", "-X", "PATCH"], patch)
                n["closed" if want == "closed" and rec.get("state", "open") == "open" else "updated"] += 1
                rec.update(hash=h, state=want)
            with open(self.map_path + ".tmp", "w") as f:    # after every call: a failure mid-way loses nothing
                json.dump(m, f, indent=1, sort_keys=True)
            os.replace(self.map_path + ".tmp", self.map_path)
        return n


def _future(cfg, data):
    raise NotImplementedError(f"tracker {cfg.get('type')!r} is a documented future adapter")


ADAPTERS = {"files": Files, "github-issues": GitHubIssues, "jira": _future, "linear": _future}


def tracker(cfg, data):
    cfg = cfg or {"type": "files"}
    return ADAPTERS[cfg.get("type", "files")](cfg, data)
