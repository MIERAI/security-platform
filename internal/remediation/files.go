// safeID is an item id usable as a file name (ledger ids are 12 hex characters).
var safeID = regexp.MustCompile(`^[A-Za-z0-9_-][A-Za-z0-9._-]*$`)

// syncCounts is the adapters' result.
type syncCounts struct{ created, updated, closed int }

func (c syncCounts) String() string {
	return fmt.Sprintf("{'created': %d, 'updated': %d, 'closed': %d}", c.created, c.updated, c.closed)
}

// itemTitle is "[severity] title" (title cut at 160 characters).
func itemTitle(it *pyjson.Object) string {
	return "[" + str(it, "severity") + "] " + cut(str(it, "title"), 160)
}

func str(it *pyjson.Object, k string) string {
	v, _ := it.Get(k)
	return pyjson.Str(v)
}

func cut(s string, n int) string {
	if utf8.RuneCountInString(s) <= n {
		return s
	}
	return string([]rune(s)[:n])
}

// itemBody is the markdown body every tracker shows.
func itemBody(it *pyjson.Object) string {
	status := "- status: " + str(it, "status")
	if it.Truthy("overdue") {
		status += " (OVERDUE)"
	}
	due := "no SLO"
	if it.Truthy("due_at") {
		due = str(it, "due_at")
	}
	opened := "- opened: " + str(it, "opened_at")
	if it.Truthy("reopened_at") {
		opened += ", reopened: " + str(it, "reopened_at") + " (" + str(it, "reopen_reason") + ")"
	}
	human := "no"
	if it.Truthy("needs_human") {
		human = "yes"
	}
	lines := []string{status,
		"- severity: " + str(it, "severity") + " (SLO class " + str(it, "slo_class") + "), due: " + due,
		"- owner: " + str(it, "owner") + " (" + str(it, "owner_source") + ")",
		"- layer / check: " + str(it, "layer") + " / `" + str(it, "check") + "`",
		"- asset: `" + str(it, "asset") + "`", opened, "- needs a human: " + human}
	if it.Truthy("closed_at") {
		lines = append(lines, "- closed: "+str(it, "closed_at")+" (time to remediate "+str(it, "time_to_remediate_days")+" d)")
	}
	if exc := it.Obj("exception"); exc != nil && exc.Len() > 0 {
		lines = append(lines, "- exception: approved by "+str(exc, "approved_by")+", expires "+str(exc, "expires"))
	}
	if it.Truthy("advisor_draft") {
		lines = append(lines, "- advisor draft (proposal only): "+str(it, "advisor_draft"))
	}
	remediationText := "(none given by the collector)"
	if it.Truthy("remediation") {
		remediationText = str(it, "remediation")
	}
	lines = append(lines, "", "## Remediation", "", remediationText, "",
		"Closure: only a collector run that covers the asset closes this item. Exceptions: exceptions.yaml (approved_by + expires).")
	return strings.Join(lines, "\n") + "\n"
}

// syncFiles is the default tracker: private markdown in DATA/tracker (<id>.md per item, README.md index).
func syncFiles(dir string, items *pyjson.Object) (syncCounts, error) {
	var n syncCounts
	for _, id := range items.Keys() {
		it := items.Obj(id)
		if it == nil {
			continue
		}
		if !safeID.MatchString(str(it, "id")) {
			continue // not a file name: such an id never comes from the ledger
		}
		if err := syncFile(dir, it, &n); err != nil {
			return n, err
		}
	}
	return n, fileio.Write(filepath.Join(dir, "README.md"), []byte(readme(items)))
}

func syncFile(dir string, it *pyjson.Object, n *syncCounts) error {
	p := filepath.Join(dir, str(it, "id")+".md")
	status := str(it, "status")
	text := "<!-- status: " + status + " -->\n# " + itemTitle(it) + "\n\nPRIVATE - attacker intelligence.\n\n" + itemBody(it)
	old, err := os.ReadFile(p) // #nosec G304 -- DATA/tracker/<id>.md, id checked
	exists := err == nil
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return fmt.Errorf("read %s: %w", p, err)
	}
	if exists && string(old) == text {
		return nil
	}
	first, _, _ := strings.Cut(string(old), "\n")
	wasOpen := exists && !strings.Contains(first, "<!-- status: fixed -->") && !strings.Contains(first, "<!-- status: false_positive -->")
	switch {
	case !exists:
		n.created++
	case wasOpen && closed(status):
		n.closed++
	default:
		n.updated++
	}
	return fileio.Write(p, []byte(text))
}

func readme(items *pyjson.Object) string {
	rows := make([]*pyjson.Object, 0, items.Len())
	for _, id := range items.Keys() {
		if it := items.Obj(id); it != nil {
			rows = append(rows, it)
		}
	}
	sort.SliceStable(rows, func(i, j int) bool { return lessRow(rows[i], rows[j]) })
	lines := []string{"# Remediation tracker", "", "PRIVATE - attacker intelligence. Generated by core/remediation.py; edit " +
		"exceptions.yaml (human approval) or fix the finding, never this file.", "",
		"| state | sev | due | owner | title | item |", "|---|---|---|---|---|---|"}
	closedN := 0
	for _, it := range rows {
		if closed(str(it, "status")) {
			closedN++
			continue
		}
		state := str(it, "status")
		if it.Truthy("overdue") {
			state = "**OVERDUE**"
		}
		due := "-"
		if it.Truthy("due_at") {
			due = cut(str(it, "due_at"), 10)
		}
		id := str(it, "id")
		lines = append(lines, "| "+state+" | "+str(it, "severity")+" | "+due+" | "+str(it, "owner")+" | "+
			strings.ReplaceAll(cut(str(it, "title"), 100), "|", "/")+" | ["+id+"]("+id+".md) |")
	}
	lines = append(lines, "", fmt.Sprintf("Closed items: %d (see items.json).", closedN))
	return strings.Join(lines, "\n") + "\n"
}

// rowKey is (closed, not open, not overdue, severity rank, due_at or "~").
func lessRow(a, b *pyjson.Object) bool {
	ka, kb := rowKey(a), rowKey(b)
	for i := 0; i < 4; i++ {
		if ka.ranks[i] != kb.ranks[i] {
			return ka.ranks[i] < kb.ranks[i]
		}
	}
	return ka.due < kb.due
}

type rowSort struct {
	ranks [4]int
	due   string
}

func rowKey(it *pyjson.Object) rowSort {
	st := str(it, "status")
	b := func(x bool) int {
		if x {
			return 1
		}
		return 0
	}
	rank, ok := map[string]int{"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}[str(it, "severity")]
	if !ok {
		rank = 9
	}
	due := "~"
	if it.Truthy("due_at") {
		due = str(it, "due_at")
	}
	return rowSort{ranks: [4]int{b(closed(st)), b(st != "open"), b(!it.Truthy("overdue")), rank}, due: due}
}
