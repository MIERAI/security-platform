#!/usr/bin/env python3
"""detections/render.py: detection catalog -> Loki ruler rules + in-cluster PrometheusRule (component `detections`).

usage: render.py [--params FILE] [--loki OUT] [--prometheus OUT] [--check]
  --params FILE   YAML mapping that overrides catalog params (an instance's allowlists, clusters, runbook base)
  --loki OUT      default detections/loki/rules.yaml (the product's default rendering, kept in git)
  --prometheus    default detections/falco/prometheus-rules.yaml
  --check         render to memory and fail if the committed files differ (CI)
Deterministic, no network. The log store evaluates loki/rules.yaml (Loki ruler, any version with LogQL v2: `| json`,
label filters, ip()); alerts carry severity, component=security-detection, detection=<id>, pillar.
"""
import argparse
import os
import re
import string
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
VERSION = open(os.path.join(HERE, "VERSION")).read().strip()
SEVERITIES = ("page", "ticket", "info")
SOURCES = ("falco", "k8s-audit", "auth", "codehost", "overlay-network")
PILLARS = ("network", "device", "workload", "identity", "data", "application")
HEADER = f"# generated by security-platform detections {VERSION} (render.py) from detections/catalog.yaml - do not edit\n"


def load(params_file=None):
    with open(os.path.join(HERE, "catalog.yaml")) as f:
        cat = yaml.safe_load(f)
    if params_file:
        with open(params_file) as f:
            over = yaml.safe_load(f) or {}
        unknown = set(over) - set(cat["params"])
        if unknown:
            raise SystemExit(f"unknown params: {sorted(unknown)}")
        cat["params"].update(over)
    return cat


def alert_name(rid):
    return "SecurityDetection" + "".join(p.capitalize() for p in rid.replace("_", "-").split("-"))


def subst(text, params):
    flat = {k: v for k, v in params.items() if isinstance(v, (str, int, float))}
    return string.Template(text).substitute(flat)


def labels(r, sev=None):
    return {"severity": sev or r["severity"], "component": "security-detection", "detection": r["id"], "pillar": r["pillar"]}


def annotations(r, params):
    a = {"summary": r["summary"], "title": r["title"], "runbook_url": f"{params['runbook_base']}/{r['id']}.md"}
    if r.get("attack"):
        a["attack"] = ", ".join(r["attack"])
    return a


def loki_rules(cat):
    p = cat["params"]
    groups = {}
    for r in cat["rules"]:
        groups.setdefault(r["source"], []).append({
            "alert": alert_name(r["id"]), "expr": subst(r["query"], p), "for": r.get("for", "0m"),
            "labels": labels(r), "annotations": annotations(r, p)})
    for c in p.get("audit_clusters") or []:
        r = {"id": "k8s-audit-silent", "title": "Kubernetes audit log went quiet", "pillar": "network", "severity": "ticket",
             "attack": ["T1562.008"], "summary": f"No API audit lines from cluster {c} for 15 minutes: the control plane is unobserved"}
        groups.setdefault("k8s-audit", []).append({
            "alert": alert_name(r["id"]), "expr": f'absent_over_time({{source="k8s-audit", cluster="{c}"}}[15m])',
            "for": "5m", "labels": dict(labels(r), cluster=c), "annotations": annotations(r, p)})
    return {"groups": [{"name": f"security-detection.{s}", "interval": "1m", "rules": rs} for s, rs in groups.items()]}


FALCO_NAMES = re.compile(r'\| rule=~?"([^"]+)"')


def falco_rule_names(r):
    """The Falco rule names a falco-source catalog rule filters on (its query's `| rule=` / `| rule=~` filter)."""
    m = FALCO_NAMES.search(r["query"])
    return m.group(1).split("|") if m else []


def prometheus_rules(cat):
    """In-cluster rules: the catalog's `prometheus` entries, plus every Falco detection again on Falco's own
    per-rule counters (label engine=falco-metrics). Runtime detection then reaches the cluster's Alertmanager even
    when the log store is down; the log-store rule adds the context (namespace, pod) to the same detection."""
    p = cat["params"]
    rs = [{"alert": alert_name(r["id"]), "expr": r["expr"], "for": r.get("for", "0m"), "labels": labels(r),
           "annotations": annotations(r, p)} for r in cat.get("prometheus", [])]
    for r in cat["rules"]:
        names = falco_rule_names(r) if r["source"] == "falco" else []
        if not names:
            continue
        sel = "|".join(re.escape(n).replace("\\ ", " ") for n in names)
        m = f'falcosecurity_falco_rules_matches_total{{rule_name=~"{sel}"}}'
        a = annotations(r, p)
        a["summary"] = f"{r['title']}: Falco rule {{{{ $labels.rule_name }}}} matched (in-cluster; details in the log store)"
        rs.append({"alert": alert_name(r["id"]),
                   # Falco exports a rule's counter only after its first match: a new series is a match too
                   "expr": (f'sum by (namespace, rule_name) (increase({m}[5m])) > 0 or '
                            f'(sum by (namespace, rule_name) ({m}) unless sum by (namespace, rule_name) ({m} offset 5m))'),
                   "for": "0m", "labels": dict(labels(r), engine="falco-metrics"), "annotations": a})
    return {"apiVersion": "monitoring.coreos.com/v1", "kind": "PrometheusRule",
            "metadata": {"name": "security-detection", "labels": {"app.kubernetes.io/part-of": "security-platform",
                                                                   "security-platform/detections-version": VERSION}},
            "spec": {"groups": [{"name": "security-detection.backstop", "rules": rs}]}}


def validate(cat):
    errs, seen = [], set()
    for r in cat["rules"] + cat.get("prometheus", []):
        rid = r.get("id", "?")
        if rid in seen:
            errs.append(f"{rid}: duplicate id")
        seen.add(rid)
        for k in ("title", "pillar", "severity", "summary"):
            if not r.get(k):
                errs.append(f"{rid}: missing {k}")
        if r.get("severity") not in SEVERITIES:
            errs.append(f"{rid}: severity {r.get('severity')!r} not in {SEVERITIES}")
        if r.get("pillar") not in PILLARS:
            errs.append(f"{rid}: pillar {r.get('pillar')!r} not in {PILLARS}")
        if r in cat["rules"] and r.get("source") not in SOURCES:
            errs.append(f"{rid}: source {r.get('source')!r} not in {SOURCES}")
        if not os.path.exists(os.path.join(ROOT, "docs", "runbooks", f"{rid}.md")):
            errs.append(f"{rid}: no runbook docs/runbooks/{rid}.md")
    if cat["params"].get("audit_clusters") and not os.path.exists(os.path.join(ROOT, "docs", "runbooks", "k8s-audit-silent.md")):
        errs.append("k8s-audit-silent: no runbook")
    try:
        loki_rules(cat)
    except (KeyError, ValueError) as e:
        errs.append(f"query parameter: {e}")
    return errs


def dump(doc):
    return HEADER + yaml.safe_dump(doc, sort_keys=False, width=200, allow_unicode=True)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--params")
    ap.add_argument("--loki", default=os.path.join(HERE, "loki", "rules.yaml"))
    ap.add_argument("--prometheus", default=os.path.join(HERE, "falco", "prometheus-rules.yaml"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    cat = load(a.params)
    errs = validate(cat)
    if errs:
        print("\n".join(errs), file=sys.stderr)
        return 1
    out = {a.loki: dump(loki_rules(cat)), a.prometheus: dump(prometheus_rules(cat))}
    rc = 0
    for path, text in out.items():
        if a.check:
            if not os.path.exists(path) or open(path).read() != text:
                print(f"{path}: not current (run detections/render.py)", file=sys.stderr)
                rc = 1
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(text)
    return rc


if __name__ == "__main__":
    sys.exit(main())
