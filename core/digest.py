#!/usr/bin/env python3
"""core digest: the weekly summary of everything that did NOT page (component `core`).

usage: digest.py --data <private data dir> [--days 7] [--now EPOCH]
Reads <data>/ledger.json (+ exceptions.yaml, latest/*.findings.json for coverage) and writes
<data>/reports/digest/<ISO year>-W<week>.md (PRIVATE: attacker intelligence). Paging is reserved for findings that
affect our assets AND (KEV OR critical+exposed) (attribute `alertable`) and for regressions; this file is where the
rest is reviewed, once a week, by a human.
"""
import argparse
import glob
import json
import os
import time

ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4}


def ts(s):
    s = str(s)
    fmt, n = ("%Y-%m-%dT%H:%M:%S", 19) if "T" in s else ("%Y-%m-%d", 10)
    return time.mktime(time.strptime(s[:n], fmt)) - time.timezone


def row(e):
    a = e.get("attributes") or {}
    tag = " **ALERTABLE**" if a.get("alertable") else ""
    ttk = f" ttk={e['time_to_know_hours']}h" if e.get("time_to_know_hours") is not None else ""
    return (f"| {e['severity']} | {e['layer']} | `{e['asset'][:70]}` | {e['title'][:110].replace('|', '/')}{tag}{ttk} | "
            f"{e['id']} |")


def remediation_section(tracker, now):
    """Overdue items and time-to-remediate vs SLO per severity (core/remediation.py keeps tracker/items.json)."""
    items = list((tracker.get("items") or {}).values())
    if not items:
        return ["", "## Remediation", "", "No tracker yet (runner job type `remediation`)."]
    slo = tracker.get("slo_seconds") or {}
    over = sorted([i for i in items if i.get("overdue")], key=lambda i: (ORDER.get(i["severity"], 9), i.get("due_at") or ""))
    L = ["", f"## Overdue remediation ({len(over)})", "",
         "| sev | " + " | ".join(ORDER) + " |", "|---|" + "---|" * len(ORDER),
         "| overdue | " + " | ".join(str(sum(1 for i in over if i["severity"] == s)) for s in ORDER) + " |",
         "| open | " + " | ".join(str(sum(1 for i in items if i["status"] == "open" and i["severity"] == s)) for s in ORDER) + " |",
         "", "| sev | due | owner | title | item |", "|---|---|---|---|---|"]
    for i in over[:200]:
        L.append(f"| {i['severity']} | {(i.get('due_at') or '')[:10]} | {i['owner']} | {i['title'][:100].replace('|', '/')} | {i['id']} |")
    un = sum(1 for i in items if i["status"] == "open" and i.get("owner") == "unassigned")
    if un:
        L += ["", f"Open items without an owner: {un} (instance `remediation.owners` / `default_owner`)."]
    L += ["", "## Time to remediate vs SLO", "", "| class | SLO (days) | closed | median (days) | max (days) | within SLO |",
          "|---|---|---|---|---|---|"]
    for cls in ["kev_exposed"] + list(ORDER):
        done = [i for i in items if i.get("slo_class") == cls and i["status"] == "fixed" and i.get("time_to_remediate_days") is not None]
        if not done and cls not in slo:
            continue
        d = sorted(i["time_to_remediate_days"] for i in done)
        lim = slo.get(cls)
        within = f"{sum(1 for x in d if lim and x * 86400 <= lim)}/{len(d)}" if lim and d else "-"
        L.append(f"| {cls} | {round(lim / 86400, 1) if lim else '-'} | {len(d)} | {d[len(d) // 2] if d else '-'} | "
                 f"{d[-1] if d else '-'} | {within} |")
    return L


def build(ledger, latest_docs, exceptions, now, days, tracker=None):
    since = now - days * 86400
    E = list(ledger.get("entries", {}).values())
    new = sorted([e for e in E if ts(e["first_seen"]) >= since], key=lambda e: (ORDER[e["severity"]], e["layer"]))
    fixed = [e for e in E if e.get("fixed_at") and ts(e["fixed_at"]) >= since]
    reopened = [e for e in E if e.get("reopened_count") and e["status"] == "open" and ts(e["last_seen"]) >= since
                and ts(e["first_seen"]) < since]
    L = [f"# Security digest {time.strftime('%G-W%V', time.gmtime(now))} (last {days} days)", "",
         "PRIVATE - attacker intelligence. Do not publish. Generated by core/digest.py.", "",
         "## SLIs", "", "| SLI | value | objective | state |", "|---|---|---|---|"]
    for k, v in sorted((ledger.get("sli") or {}).items()):
        L.append(f"| {k} | {v['value']} | <= {v['target']} | {'OK' if v['ok'] else '**BREACH**'} |")
    L += ["", f"## New findings ({len(new)})", "",
          "Paged already: rows marked ALERTABLE (KEV, or critical on an exposed asset). Everything else is for this review.", "",
          "| sev | layer | asset | title | id |", "|---|---|---|---|---|"] + [row(e) for e in new[:300]]
    if len(new) > 300:
        L.append(f"| … | | | {len(new) - 300} more in ledger.json | |")
    L += ["", f"## Fixed ({len(fixed)})", "", "| sev | layer | asset | title | id |", "|---|---|---|---|---|"]
    L += [row(e) + f" {e.get('time_to_fix_days')} d" for e in fixed[:200]]
    L += ["", f"## Regressions still open ({len(reopened)})", ""] + [row(e) for e in reopened]
    L += remediation_section(tracker or {}, now)
    L += ["", "## Exceptions", "", "| id | expires | approved by | state |", "|---|---|---|---|"]
    for fid, x in sorted(exceptions.items()):
        exp = ts(str(x.get("expires", "1970-01-01")))
        state = "EXPIRED" if exp < now else ("expires within 14 days" if exp - now < 14 * 86400 else "active")
        L.append(f"| {fid} | {x.get('expires')} | {x.get('approved_by', '(none: ignored)')} | {state} |")
    L += ["", "## Platform health (coverage: no findings != secure)", "", "| collector | finished | gaps |", "|---|---|---|"]
    for d in latest_docs:
        gaps = [g for g in d["coverage"] if g["status"] == "gap"]
        L.append(f"| {d['collector']['name']} {d['collector']['version']} | {d['run']['finished_at']} | {len(gaps)} |")
        for g in gaps[:20]:
            L.append(f"|  | `{g['asset'][:60]}` | {g.get('reason', '')[:100].replace('|', '/')} |")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True)
    ap.add_argument("--days", type=int, default=7)
    ap.add_argument("--now", type=float)
    a = ap.parse_args()
    now = a.now or time.time()
    ledger = json.load(open(os.path.join(a.data, "ledger.json")))
    docs = [json.load(open(p)) for p in sorted(glob.glob(os.path.join(a.data, "latest", "*.findings.json")))]
    exc = {}
    ep = os.path.join(a.data, "exceptions.yaml")
    if os.path.exists(ep):
        try:
            import yaml
            exc = (yaml.safe_load(open(ep)) or {}).get("exceptions") or {}
        except ImportError:
            exc = {}
    out = os.path.join(a.data, "reports", "digest", time.strftime("%G-W%V", time.gmtime(now)) + ".md")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    tp = os.path.join(a.data, "tracker", "items.json")
    tracker = json.load(open(tp)) if os.path.exists(tp) else None
    with open(out, "w") as f:
        f.write(build(ledger, docs, exc, now, a.days, tracker))
    print(out)


if __name__ == "__main__":
    main()
